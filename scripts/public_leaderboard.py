"""Re-score public Eval submissions; persist an append-only GitHub-backed ledger.

Only JSON and bounded gzip CSV are consumed. No participant code or URLs run.
The GitHub identity/timestamp come from the issue API, never from the package.
"""
import argparse
import base64
import datetime as dt
import gzip
import hashlib
import io
import json
import os
import re
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

from server.scoring import parse_submission
from server.scoring_v2 import score

ROOT = Path(__file__).resolve().parent.parent
REPO = 'jhparktime/TURST-YOUR-EARS'
BRANCH = 'leaderboard-data'
FORMAT = 'tye-public-submission-v1'
SCHEMA = 'tye-public-board-v1'
MAX_PACKET = 60_000
MAX_CSV = 2 * 1024 * 1024
KST = dt.timezone(dt.timedelta(hours=9))
SUMMARY_KEYS = ('micro_cer', 'macro_cer', 'micro_wer', 'cer_improvement_pp',
                'slot_restoration_rate', 'harmful_edit_rate', 'correction_precision',
                'correction_f1', 'unwanted_insertion_rate', 'clean_change_rate', 'utterances', 'counts')


def manifest_hash():
    return hashlib.sha256((ROOT/'web/data-v2/eval.json').read_bytes()).hexdigest()


def empty_board():
    return dict(schema=SCHEMA, dataset='tye-ko-asr-v2-eval', protocol='ko-correction-v2',
                manifest_sha256=manifest_hash(), updated_at=None, entries=[], history=[], checks=[])


def unpack(body):
    if not isinstance(body, str) or len(body) > 65_536:
        raise ValueError('Submission body exceeds the size limit.')
    # GitHub issue forms wrap the one JSON field in a heading / fenced block.
    start, end = body.find('{'), body.rfind('}')
    if start < 0 or end < start or end-start+1 > MAX_PACKET:
        raise ValueError('Paste the result package generated by the website (max 60,000 characters).')
    try:
        packet = json.loads(body[start:end+1])
    except (ValueError, RecursionError):
        raise ValueError('Result package is not valid JSON.') from None
    if not isinstance(packet, dict) or packet.get('format') != FORMAT or packet.get('consent') is not True:
        raise ValueError('Unsupported result package or missing public-sharing consent.')
    if packet.get('manifest_sha256') != manifest_hash():
        raise ValueError('Dataset version mismatch. Generate a new package on the website.')
    for field, limit in [('team', 60), ('method', 160), ('code_url', 300)]:
        value = packet.get(field)
        if not isinstance(value, str) or not value.strip() or len(value) > limit or any(ord(c)<32 for c in value):
            raise ValueError('Invalid team, method or code URL.')
        packet[field] = value.strip()
    url = urllib.parse.urlsplit(packet['code_url'])
    if url.scheme != 'https' or not url.hostname or url.username or url.password:
        raise ValueError('Provide a public HTTPS link to the code or reproduction instructions.')
    if packet.get('encoding') != 'gzip+base64':
        raise ValueError('Unsupported CSV encoding.')
    try:
        compressed = base64.b64decode(packet.get('csv', ''), validate=True)
        with gzip.GzipFile(fileobj=io.BytesIO(compressed)) as stream:
            csv = stream.read(MAX_CSV+1)
    except (ValueError, TypeError, OSError, EOFError):
        raise ValueError('Invalid compressed CSV.') from None
    if len(csv) > MAX_CSV or hashlib.sha256(csv).hexdigest() != packet.get('csv_sha256'):
        raise ValueError('CSV size or checksum does not match.')
    return packet, csv


def rank_board(board):
    best = {}
    for row in board['history']:
        if row['status'] != 'accepted':
            continue
        key = row['github_id']
        if key not in best or row['metrics']['micro_cer'] < best[key]['metrics']['micro_cer']:
            best[key] = row
    rows = sorted(best.values(), key=lambda r: (r['metrics']['micro_cer'], r['issue']))
    previous, rank = None, 0
    board['entries'] = []
    for index, row in enumerate(rows, 1):
        if row['metrics']['micro_cer'] != previous:
            rank, previous = index, row['metrics']['micro_cer']
        board['entries'].append(dict(row, rank=rank, submissions=sum(
            r['status']=='accepted' and r['github_id']==row['github_id'] for r in board['history'])))


def ingest(board, issue):
    """Exactly once per issue; identical CSVs don't consume daily valid quota."""
    if board.get('schema') != SCHEMA or board.get('manifest_sha256') != manifest_hash():
        raise ValueError('Stored leaderboard version does not match this scorer.')
    number = issue['number']
    if any(row['issue']==number for row in board['history']):
        return False
    identity = issue['user']
    if not isinstance(number, int) or not isinstance(identity.get('id'), int) or not re.fullmatch(r'[A-Za-z0-9-]{1,39}', identity.get('login', '')):
        raise ValueError('Invalid GitHub issue identity.')
    created = dt.datetime.fromisoformat(issue['created_at'].replace('Z', '+00:00'))
    day = created.astimezone(KST).date().isoformat()
    row = dict(issue=number, issue_url=f'https://github.com/{REPO}/issues/{number}',
               github_id=identity['id'], github_login=identity['login'],
               submitted_at=issue['created_at'], day_kst=day,
               body_sha256=hashlib.sha256((issue.get('body') or '').encode()).hexdigest())
    try:
        packet, csv = unpack(issue.get('body'))
        row.update(team=packet['team'], method=packet['method'], code_url=packet['code_url'], csv_sha256=packet['csv_sha256'])
        own = [r for r in board['history'] if r['github_id']==identity['id'] and r['status']=='accepted']
        # Bind the first registered team name to this submitting account.
        if own and own[0]['team'] != row['team']:
            raise ValueError('Use the team name from your first accepted submission.')
        if any(r['team'].casefold()==row['team'].casefold() and r['github_id']!=identity['id'] for r in board['history'] if r['status']=='accepted'):
            raise ValueError('This team name is already registered by another GitHub account.')
        duplicate = next((r for r in own if r['csv_sha256']==row['csv_sha256']), None)
        if duplicate:
            row.update(status='duplicate', duplicate_of=duplicate['issue'], metrics=duplicate['metrics'])
        else:
            if sum(r['day_kst']==day for r in own) >= 5:
                raise ValueError('Five valid new submissions per account per KST day; reset 00:00 KST.')
            references = json.loads((ROOT/'web/data-v2/eval.json').read_text())['items']
            metrics = score(parse_submission(csv), references)
            row.update(status='accepted', metrics={key: metrics[key] for key in SUMMARY_KEYS})
    except ValueError as exc:
        row.update(status='rejected', reason=str(exc)[:400])
    board['history'].append(row)
    board['updated_at'] = dt.datetime.now(dt.timezone.utc).isoformat()
    rank_board(board)
    return True


def api(path, token, method='GET', data=None):
    headers = {'Accept': 'application/vnd.github+json', 'Authorization': 'Bearer '+token,
               'X-GitHub-Api-Version': '2022-11-28', 'User-Agent': 'TYE-public-eval'}
    if data is not None:
        headers['Content-Type'] = 'application/json'
    request = urllib.request.Request('https://api.github.com/repos/'+REPO+'/'+path,
        headers=headers, method=method, data=None if data is None else json.dumps(data).encode())
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def run(smoke=False):
    token = os.environ['GH_TOKEN']
    sha = None
    try:
        saved = api('contents/public-eval.json?ref='+BRANCH, token)
        board = json.loads(base64.b64decode(saved['content']))
        sha = saved['sha']
    except urllib.error.HTTPError as exc:
        if exc.code != 404:
            raise
        board = empty_board()
    changed = False
    # Reconcile all submissions, including those whose event was delayed/cancelled.
    pending = []
    for page in range(1, 11):
        batch = api(f'issues?state=all&sort=created&direction=asc&per_page=100&page={page}', token)
        pending.extend(r for r in batch if 'pull_request' not in r and r['title'].startswith('[Public Eval]'))
        if len(batch)<100:
            break
    for issue in sorted(pending, key=lambda r: (r['created_at'], r['number'])):
        changed = ingest(board, issue) or changed
    if smoke:
        csv = (ROOT/'web/data-v2/eval-copy.csv').read_bytes()
        references = json.loads((ROOT/'web/data-v2/eval.json').read_text())['items']
        measured = score(parse_submission(csv), references)
        expected = next(r['metrics'] for r in json.loads((ROOT/'web/data-v2/baselines.json').read_text())['entries'] if r['baseline']=='Copy draft' and r['split']=='eval')
        assert measured == expected
        board['checks'].append(dict(kind='organizer_storage_check', run_id=os.environ.get('GITHUB_RUN_ID'),
            at=dt.datetime.now(dt.timezone.utc).isoformat(), micro_cer=measured['micro_cer'], utterances=measured['utterances']))
        board['updated_at']=dt.datetime.now(dt.timezone.utc).isoformat()
        changed = True
    if not changed and sha:
        print('No new submissions; stored history retained.')
        return
    if sha is None:
        try:
            api('git/ref/heads/'+BRANCH, token)
        except urllib.error.HTTPError as exc:
            if exc.code != 404:
                raise
            head=api('git/ref/heads/main',token)['object']['sha']
            api('git/refs', token, 'POST', {'ref':'refs/heads/'+BRANCH, 'sha':head})
    payload=dict(message='Record verified public Eval results', branch=BRANCH,
        content=base64.b64encode((json.dumps(board,ensure_ascii=False,indent=2)+'\n').encode()).decode())
    if sha:
        payload['sha']=sha
    api('contents/public-eval.json',token,'PUT',payload)
    # Verify the exact saved state through the authenticated source, no local-only success.
    check=api('contents/public-eval.json?ref='+BRANCH,token)
    assert json.loads(base64.b64decode(check['content']))==board
    print(json.dumps({'accepted':sum(r['status']=='accepted' for r in board['history']),
        'teams':len(board['entries']),'history':len(board['history']),'storage_checks':len(board['checks'])}))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--smoke-test',action='store_true')
    run(parser.parse_args().smoke_test)
